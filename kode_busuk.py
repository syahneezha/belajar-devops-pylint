"""Modul contoh sederhana."""


def x(nilai_a, nilai_b):
    """Menjumlahkan dua nilai dan menampilkan hasilnya.

    Args:
        nilai_a: Nilai pertama.
        nilai_b: Nilai kedua.

    Returns:
        Hasil penjumlahan nilai_a dan nilai_b.
    """
    hasil = nilai_a + nilai_b
    print(hasil)
    return hasil


x(1, 2)
